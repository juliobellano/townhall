#!/usr/bin/env python3
"""Tax filing report (v1).

Town Hall tool contract:
  python v1.py --schema   -> prints this tool's input JSON Schema
  python v1.py            -> reads JSON inputs on stdin, writes a JSON result on stdout
Failures print {"error": "..."} on stdout and exit with a non-zero status.
Returns the report as a PDF file, tax-filing.pdf, in the reserved "_files" key
(name, mime_type, base64). Town Hall stores it and gives back a download link.
Reads branch databases (*.db) from $TOWNHALL_DATA_DIR. Buckets by UTC month.
"""
import base64
import glob
import json
import os
import re
import sqlite3
import sys
from datetime import datetime

SCHEMA = {
    "type": "object",
    "properties": {
        "month": {"type": "string", "pattern": r"^\d{4}-\d{2}$", "description": "Report month, YYYY-MM"},
        "branches": {
            "type": "array",
            "items": {"type": "string"},
            "description": "Branch names to include. Defaults to all branches.",
        },
    },
    "required": ["month"],
    "additionalProperties": False,
}


def pdf_text(s):
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def tax_filing_pdf(report):
    """A one-page PDF of the report. Byte-for-byte deterministic: no dates, no IDs."""
    lines = [
        ("F2", 20, 56, 770, "Tax filing report"),
        ("F1", 11, 56, 744, f"Period: {report['month']}"),
        ("F1", 11, 56, 728, f"Month cutoff timezone: {report['timezone']}"),
        ("F1", 11, 56, 712, "Source: branch databases (read only)"),
        ("F4", 10, 56, 676, f"{'Branch':<16}{'Transactions':>14}{'Total':>16}"),
    ]
    y = 658
    for b in report["branches"]:
        lines.append(("F3", 10, 56, y, f"{b['branch']:<16}{b['transactions']:>14,}{b['total']:>16,}"))
        y -= 16
    lines.append(("F4", 10, 56, y - 8, f"{'Grand total':<16}{sum(b['transactions'] for b in report['branches']):>14,}{report['grand_total']:>16,}"))
    lines.append(("F1", 8, 56, 56, "Generated by the Town Hall tool tax-filing-report."))
    ops = []
    for font, size, x, ty, text in lines:
        ops.append(f"BT /{font} {size} Tf {x} {ty} Td ({pdf_text(text)}) Tj ET")
    ops.append(f"0.5 w 56 {y + 4} m 332 {y + 4} l S 56 670 m 332 670 l S")
    content = "\n".join(ops).encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R /F2 6 0 R /F3 7 0 R /F4 8 0 R >> >> >>",
        b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier-Bold >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode() + b"0000000000 65535 f \n"
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def fail(message: str):
    print(json.dumps({"error": message}))
    sys.exit(2)


def main():
    if "--schema" in sys.argv:
        print(json.dumps(SCHEMA, sort_keys=True))
        return
    try:
        inputs = json.load(sys.stdin)
    except json.JSONDecodeError:
        fail("inputs must be valid JSON")
    month = inputs.get("month")
    if not isinstance(month, str) or not re.match(r"^\d{4}-\d{2}$", month):
        fail("month must be a string like 2026-10")
    wanted = inputs.get("branches")
    data_dir = os.environ.get("TOWNHALL_DATA_DIR")
    if not data_dir:
        fail("TOWNHALL_DATA_DIR is not set")
    paths = sorted(glob.glob(os.path.join(data_dir, "*.db")))
    available = [os.path.splitext(os.path.basename(p))[0] for p in paths]
    if wanted:
        unknown = [b for b in wanted if b not in available]
        if unknown:
            fail(f"unknown branch: {', '.join(unknown)}")
    result = []
    for path, name in zip(paths, available):
        if wanted and name not in wanted:
            continue
        con = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
        count, total = 0, 0
        for ts, amount in con.execute("SELECT created_at_utc, amount FROM transactions"):
            when = datetime.fromisoformat(ts.replace("Z", "+00:00"))
            if when.strftime("%Y-%m") == month:
                count += 1
                total += amount
        con.close()
        result.append({"branch": name, "transactions": count, "total": total})
    report = {"month": month, "timezone": "UTC", "branches": result, "grand_total": sum(r["total"] for r in result)}
    pdf = tax_filing_pdf(report)
    report["_files"] = [{"name": "tax-filing.pdf", "mime_type": "application/pdf", "base64": base64.b64encode(pdf).decode("ascii")}]
    print(json.dumps(report, sort_keys=True))


if __name__ == "__main__":
    main()
